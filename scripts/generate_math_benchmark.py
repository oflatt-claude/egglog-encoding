#!/usr/bin/env python3
"""Generate the fixed current-egg comparison Math workload."""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = ROOT / "benchmarks/math-microbenchmark/math.egg"
BASE_INCLUDE = "benchmarks/math-microbenchmark/base.egg"
ITERATIONS = 11
EGG_CHECK_LEFT = "(+ (cos x) (cos x))"
EGG_CHECK_RIGHT = "(d x (+ (sin x) (sin x)))"
EGGLOG_CHECK_LEFT = '(Add (Cos (Var "x")) (Cos (Var "x")))'
EGGLOG_CHECK_RIGHT = '(Diff (Var "x") (Add (Sin (Var "x")) (Sin (Var "x"))))'


def render_math() -> str:
    runs = "\n".join("  (run)" for _ in range(ITERATIONS))
    return (
        "; Generated by scripts/generate_math_benchmark.py.\n"
        "; Current egg and egglog both establish the terminal equality on run 11, not run 10.\n"
        f'(include "{BASE_INCLUDE}")\n\n'
        f"(run-schedule (seq\n{runs}))\n"
        f"(check (= {EGGLOG_CHECK_LEFT} {EGGLOG_CHECK_RIGHT}))\n"
    )


def write_fixture() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(render_math(), encoding="utf-8")


def check_fixture() -> bool:
    if OUTPUT_PATH.is_file() and OUTPUT_PATH.read_text(encoding="utf-8") == render_math():
        return True
    print(f"stale generated Math fixture: {OUTPUT_PATH.relative_to(ROOT)}", file=sys.stderr)
    return False


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the fixed fixture")
    mode.add_argument("--check", action="store_true", help="check the committed fixture")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    if args.write:
        write_fixture()
        return 0
    return 0 if check_fixture() else 1


if __name__ == "__main__":
    raise SystemExit(main())

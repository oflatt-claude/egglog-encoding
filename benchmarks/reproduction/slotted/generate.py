"""Regenerate self-contained slotted source inputs and exact native reference specs.

Run ``python -m benchmarks.reproduction.slotted.generate`` from the repository root. Collection
only reads the checked-in inputs; it never imports this generator or slotted's
graph verification machinery.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import ROOT, reference, workloads

INPUTS = ROOT / "benchmarks/slotted/inputs"


def frozen_inputs() -> dict[Path, str]:
    """Expand source includes and retain each workload's exact schedule and goal."""

    def expand(source: str) -> list[str]:
        forms = []
        for form in reference.parse(source):
            if form[0] == "include":
                forms.extend(expand((ROOT / json.loads(form[1])).read_text()))
            else:
                forms.append(reference.render(form))
        return forms

    selected = [workloads.array_workload(n, rounds=6) for n in range(11)]
    selected += [workloads.sdql_workload(*case) for case in workloads.pf.WORKLOADS]
    selected += [
        workloads.logic_workload(path) for path in sorted(workloads.LOGIC_FIXTURES.glob("first-order-logic*.egg"))
    ]
    result = {}
    for workload in selected:
        path = Path(workload.study) / f"{workload.case}.egg"
        result[path] = (
            "; Generated by python -m benchmarks.slotted.generate.\n" + "\n".join(expand(workload.program)) + "\n"
        )
        result[path.with_suffix(".ref")] = (
            json.dumps(
                {
                    "multi": workload.multi,
                    "nested": workload.nested,
                    "unsupported_reason": workload.unsupported_reason,
                },
                indent=2,
                ensure_ascii=False,
            )
            + "\n"
        )
    return result


def main() -> None:
    """Regeneration is explicit; --check compares bytes without building or running."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify checked-in bytes instead of writing")
    args = parser.parse_args()
    generated = frozen_inputs()
    if args.check:
        existing = {path.relative_to(INPUTS) for path in INPUTS.rglob("*") if path.suffix in (".egg", ".ref")}
        if existing != set(generated):
            raise SystemExit("frozen input set differs from the reproduction generator")
        changed = [str(path) for path, source in generated.items() if (INPUTS / path).read_text() != source]
        if changed:
            raise SystemExit("frozen bytes differ: " + ", ".join(changed))
        print(f"{len(generated)} frozen files match the explicit reproduction generator")
        return
    for relative, source in generated.items():
        path = INPUTS / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)


if __name__ == "__main__":
    main()
